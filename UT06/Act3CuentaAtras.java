package UT06;

public class Act3CuentaAtras {
    public static void main(String[] args) {
        
        int cuentaAtras = 8;

        while (cuentaAtras >= 1) {
            System.out.println("Cuenta: " +cuentaAtras);
            cuentaAtras--;
        }
        System.out.println("Comienza el torneo");
    }
}
